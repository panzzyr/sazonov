// Packs only the owner's task1006-1 PNGs, without resampling their alpha.
// Usage: node scripts/build-church-slavonic.mjs [source-directory] [--check]
// Sheets are written locally; the generated TypeScript is printed on stdout.
// --check verifies both committed outputs without modifying them.
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";
import { packShelves } from "../apps/glyph-art/src/sheetPacking.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = path.resolve(process.argv.slice(2).find((arg) => arg !== "--check")
  ?? path.join(root, "../task1006-1/ASCII 1st vitrina"));
const check = process.argv.includes("--check");
const output = path.join(root, "apps/glyph-art/public/presets/church-slavonic-vedomosti");
const hash = (data) => createHash("sha256").update(data).digest("hex");
// The owner removed the ornament from the preset; keep its source file intact.
const excluded = new Set(["a0009.png"]);
const names = (await readdir(source)).filter((name) => /\.png$/i.test(name))
  .filter((name) => !excluded.has(name))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
if (!names.length) throw new Error("No PNG symbols in the supplied directory.");

const marks = [];
for (const name of names) {
  const original = await readFile(path.join(source, name));
  if (!(await sharp(original).metadata()).hasAlpha) throw new Error(`${name}: expected an alpha mask.`);
  const { data, info } = await sharp(original).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const paper = new Uint8Array(info.width * info.height);
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      const alpha = data[(y * info.width + x) * 4 + 3];
      paper[y * info.width + x] = 255 - alpha;
      if (alpha <= 255 * 0.02) continue;
      left = Math.min(left, x); right = Math.max(right, x);
      top = Math.min(top, y); bottom = Math.max(bottom, y);
    }
  }
  if (right < left) throw new Error(`${name}: empty symbol; do not silently drop curated inputs.`);
  let ink = 0;
  for (let y = top; y <= bottom; y++) {
    for (let x = left; x <= right; x++) ink += 255 - paper[y * info.width + x];
  }
  const density = ink / 255 / ((right - left + 1) * (bottom - top + 1));
  const aspect = (right - left + 1) / (bottom - top + 1);
  marks.push({ name, sha256: hash(original), inkHash: hash(paper),
    width: info.width, height: info.height, density, aspect, paper });
}
const packed = packShelves(marks.map(({ width, height }) => [width, height]));
if (!check) await mkdir(output, { recursive: true });
const sheets = [];
for (const [index, sheet] of packed.sheets.entries()) {
  const buffer = await sharp({ create: { ...sheet, channels: 3, background: "#fff" } })
    .composite(await Promise.all(marks.flatMap((mark, markIndex) => {
      const place = packed.places[markIndex];
      if (place.sheet !== index) return [];
      return [sharp(mark.paper, { raw: { width: mark.width, height: mark.height, channels: 1 } })
        .png().toBuffer().then((input) => ({ input, left: place.x, top: place.y }))];
    })))
    .webp({ lossless: true, effort: 6 }).toBuffer();
  const name = `sheet-${index}.webp`;
  if (check) {
    if (!(await readFile(path.join(output, name))).equals(buffer)) throw new Error(`Stale ${name}.`);
  } else await writeFile(path.join(output, name), buffer);
  sheets.push([`presets/church-slavonic-vedomosti/${name}`, sheet.width, sheet.height]);
}

const maxSize = 1.45;
const cellInk = ({ density, aspect }) => density * Math.min(aspect, 1 / aspect);
// A small curated set reuses its symbols across levels. Keep at least forty
// eligible marks in the shadows, but never size a sparse mark past the ceiling.
const sorted = marks.map((mark, index) => ({ index, coverage: cellInk(mark) }))
  .sort((a, b) => b.coverage - a.coverage || a.index - b.index);
const peak = Math.min(0.75, sorted[Math.min(40, marks.length) - 1].coverage
  * maxSize ** 2 / (11.5 / 12) ** 1.45);
const levels = Array.from({ length: 12 }, (_, level) => {
  const wanted = peak * ((level + 0.5) / 12) ** 1.45;
  return sorted.filter(({ coverage }) => Math.sqrt(wanted / coverage) <= maxSize + 1e-9)
    .map(({ index }) => index);
});
if (new Set(levels.flat()).size !== marks.length) throw new Error("Not every supplied symbol prints.");
const entries = marks.map(({ name, sha256, inkHash, width, height, density, aspect }, index) => {
  const place = packed.places[index];
  return { name, sha256, inkHash, sheet: place.sheet, rect: [place.x, place.y, width, height], density, aspect };
});
const module = [
  `// Generated by scripts/build-church-slavonic.mjs. ${marks.length} task1006-1 PNGs; a0009.png is excluded.`,
  "export const churchSlavonicSheets: [string, number, number][] = " + JSON.stringify(sheets) + ";",
  "export const churchSlavonicMarks: { name: string; sha256: string; inkHash: string; sheet: number; rect: [number, number, number, number]; density: number; aspect: number }[] = [",
  ...entries.map((entry) => "  " + JSON.stringify(entry) + ","),
  "];",
  `export const churchSlavonicPeak = ${peak};`,
  `export const churchSlavonicMaxSize = ${maxSize};`,
  "export const churchSlavonicLevels: number[][] = [",
  ...levels.map((level) => "  " + JSON.stringify(level) + ","),
  "];", "",
].join("\n");
if (check) {
  const committed = await readFile(path.join(root, "apps/glyph-art/src/generatedChurchSlavonic.ts"), "utf8");
  if (committed !== module) throw new Error("Stale generatedChurchSlavonic.ts.");
} else process.stdout.write(module);
console.error(`${marks.length} original symbols, ${sheets.length} lossless sheet(s), peak ${peak.toFixed(3)}, pools ${levels.map((level) => level.length).join("/")}`);

// Screen the existing measured catalogue without rewriting sheets or mark ids.
// Prints a generated module; --check compares it with the committed version.
import { readFileSync } from "node:fs";
import { presetMetrics } from "../apps/glyph-art/src/generatedPresetMetrics.ts";
import { rejectsScan, scanBlurLimit } from "../apps/glyph-art/src/engine/scanQuality.ts";

const groups = new Map();
for (const [id, metric] of Object.entries(presetMetrics)) {
  const [, group, index] = /^preset-(.+)-(\d+)$/.exec(id);
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push({ index: Number(index), ...metric });
}
const rejected = {};
for (const [group, marks] of groups) {
  const limit = scanBlurLimit(marks);
  const indices = marks.filter((mark) => rejectsScan(mark, limit)).map((mark) => mark.index);
  if (indices.length) rejected[group] = indices;
  console.error(`${group}: ${indices.length}/${marks.length} screened out; blur limit ${limit.toFixed(3)} px`);
}
const module = "// Generated by scripts/audit-glyph-quality.mjs from the measured catalogue.\n"
  + "// Excluded from automatic selection; sheets and ids remain available to saved projects.\n"
  + `export const rejectedScanIndices: Record<string, number[]> = ${JSON.stringify(rejected, null, 2)};\n`;
if (process.argv.includes("--check")) {
  const existing = readFileSync(new URL("../apps/glyph-art/src/generatedPresetQuality.ts", import.meta.url), "utf8");
  if (module !== existing) throw new Error("The scan quality catalogue is stale; regenerate it.");
} else {
  process.stdout.write(module);
}

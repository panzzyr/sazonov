// One-time vectorization of every committed scan, including the curated set.
// No original scans or extra packages needed. Node 22+ supports these TS imports.
// node scripts/build-glyph-vectors.mjs [--check]
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";
import { presetGroups, presetSizeAlphabet } from "../apps/glyph-art/src/generatedPresets.ts";
import { churchSlavonicMarks, churchSlavonicSheets } from "../apps/glyph-art/src/generatedChurchSlavonic.ts";
import { packShelves } from "../apps/glyph-art/src/sheetPacking.ts";
import { traceGlyph } from "../apps/glyph-art/src/engine/glyphOutline.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = path.join(root, "apps/glyph-art/src/preset-vectors");
const check = process.argv.includes("--check");
if (!check) await mkdir(output, { recursive: true });
const groups = presetGroups.map(group => {
  const sizes = Array.from({ length: group.sizes.length / 2 }, (_, index) => [
    presetSizeAlphabet.indexOf(group.sizes[index * 2]) + 1,
    presetSizeAlphabet.indexOf(group.sizes[index * 2 + 1]) + 1,
  ]);
  return { id: group.id, sheets: group.sheets, marks: packShelves(sizes).places.map((place, index) =>
    ({ sheet: place.sheet, rect: [place.x, place.y, ...sizes[index]] })) };
});
groups.push({ id: "church-slavonic-vedomosti", sheets: churchSlavonicSheets, marks: churchSlavonicMarks });
let total = 0;
for (const group of groups) {
  const hash = createHash("sha256");
  const sheets = [];
  for (const [source] of group.sheets) {
    const buffer = await readFile(path.join(root, "apps/glyph-art/public", source));
    hash.update(buffer);
    sheets.push(await sharp(buffer).ensureAlpha().raw().toBuffer({ resolveWithObject: true }));
  }
  const packed = group.marks.map(({ sheet, rect: [x, y, width, height] }) => {
    const { data, info } = sheets[sheet];
    let left = width, top = height, right = -1, bottom = -1;
    const ink = new Uint8ClampedArray(width * height);
    for (let row = 0; row < height; row++) {
      for (let col = 0; col < width; col++) {
        const at = ((y + row) * info.width + x + col) * info.channels;
        const alpha = data[at + 3] / 255;
        const value = alpha * (255 - (0.2126 * data[at] + 0.7152 * data[at + 1] + 0.0722 * data[at + 2]));
        ink[row * width + col] = value;
        if (value <= 255 * 0.02) continue;
        left = Math.min(left, col); right = Math.max(right, col);
        top = Math.min(top, row); bottom = Math.max(bottom, row);
      }
    }
    if (right < left) throw new Error(`${group.id}: empty committed mark.`);
    const w = right - left + 1, h = bottom - top + 1;
    const cropped = new Uint8ClampedArray(w * h);
    for (let row = 0; row < h; row++) cropped.set(ink.subarray((row + top) * width + left, (row + top) * width + left + w), row * w);
    const result = traceGlyph(cropped, w, h);
    if (!result[3] || result[2] <= 0) throw new Error(`${group.id}: tracing lost a symbol.`);
    return [w, h, Number(result[2].toFixed(6)), result[3]];
  });
  const module = `// Generated by scripts/build-glyph-vectors.mjs. Source SHA-256: ${hash.digest("hex")}\n`
    + `// All ${packed.length} marks in stable catalogue order. No raster artwork.\n`
    + `export default ${JSON.stringify(packed)};\n`;
  const target = path.join(output, `${group.id}.ts`);
  if (check) {
    if (await readFile(target, "utf8") !== module) throw new Error(`Stale vectors: ${group.id}.`);
  } else await writeFile(target, module);
  total += packed.length;
  console.log(`${group.id}: ${packed.length} vectors, ${Buffer.byteLength(module)} bytes`);
}
console.log(`${total} vectorized scans across ${groups.length} groups.`);
